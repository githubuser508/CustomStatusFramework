static GonDoc g_gonDoc;


/* ====================================================================
 *  C Extension Registration
 * ==================================================================== */

void CSF_RegisterExtension(const char* statusName, int slot, void* fnPtr)
{
    CSF_Extension* ext;

    if (g_extensionCount >= CSF_MAX_EXTENSIONS)
    {
        SLog("[CSF] WARNING: extension table full, cannot register %s slot %d",
             statusName, slot);
        return;
    }

    ext = &g_extensions[g_extensionCount++];
    strncpy(ext->status_name, statusName, GON_MAX_STRING_LEN - 1);
    ext->status_name[GON_MAX_STRING_LEN - 1] = '\0';
    ext->slot_index = slot;
    ext->fn_ptr = fnPtr;

    SLog("[CSF] Extension registered: %s slot %d -> 0x%p",
         statusName, slot, fnPtr);
}


/* ====================================================================
 *  Behavior registry -named built-in slot behaviors
 *
 *  See the long comment block in csf_core.h for the rationale.  This
 *  section implements:
 *
 *    CSF_RegisterBehavior / CSF_FindBehavior
 *      -- storage and lookup
 *
 *    CSF_Dispatch_<Sig>_Slot<N>_<Mode>
 *      -- C dispatchers generated by DEFINE_<SIG>_DISPATCHERS macros.
 *         One pair (AFTER/REPLACE) per (signature, slot) because a
 *         dispatcher has to know which slot it services without an
 *         extra argument, so the slot index has to be baked into the
 *         function body.  See the "Dispatcher generator macros" block
 *         below for why the macro stamp-out is necessary.
 *
 *    CSF_PickDispatcher
 *      -- table lookup from slot index to the pair of dispatchers for
 *         that slot.  Adding a new slot = adding a macro invocation
 *         and a table row.
 *
 *    CSF_ResolveBehaviorOverride
 *      -- called by CSF_DefaultBuildVtable when it encounters a
 *         slot_override whose behavior_name is set.  Installs the
 *         dispatcher and caches donor fn for chaining.
 *
 *    CSF_ResolvePendingBehaviorBindings
 *      -- called by CSF_RegisterBehavior after a new entry lands, to
 *         re-sweep any slot_overrides that were parked pending the
 *         behavior's arrival.
 * ==================================================================== */

/* -- Behavior lookup helpers --------------------------------------- */

const CSF_Behavior* CSF_FindBehavior(const char* name)
{
    int i;
    if (!name) return NULL;
    for (i = 0; i < g_behaviorCount; i++)
    {
        if (strcmp(g_behaviors[i].name, name) == 0)
            return &g_behaviors[i];
    }
    return NULL;
}

/* Given a status def and a slot index, find the slot_override record.
 * Returns NULL if the def has no override for that slot. */
static CSF_SlotOverride* CSF_FindOverrideForSlot(
    const CSF_StatusDef* def, int slotIndex)
{
    int i;
    if (!def || !def->slot_overrides) return NULL;
    for (i = 0; i < def->slot_override_count; i++)
    {
        if (def->slot_overrides[i].slot_index == slotIndex)
            return (CSF_SlotOverride*)&def->slot_overrides[i];
    }
    return NULL;
}

/* Given an instance, walk its vtable pointer back to the status def
 * that owns it.  Linear scan over the <= CSF_MAX_STATUSES custom
 * status defs; each def has a unique custom_vtable pointer, so the
 * match is exact.  Returns NULL if the instance's vtable isn't a
 * custom vtable (shouldn't happen when the dispatcher is called -by
 * construction we only install the dispatcher into custom vtables). */
static const CSF_StatusDef* CSF_FindDefByInstance(void* instance)
{
    int i;
    void** instVt;
    if (!instance) return NULL;
    instVt = *(void***)instance;
    for (i = 0; i < CSF_MAX_STATUSES; i++)
    {
        const CSF_StatusDef* def = CSF_GetStatusDef(i);
        if (!def) break;
        if (def->custom_vtable == instVt)
            return def;
    }
    return NULL;
}

/* Find the slot-override record for (instance, slot) in one call. */
static CSF_SlotOverride* CSF_FindOverrideForInstance(void* instance, int slot)
{
    const CSF_StatusDef* def = CSF_FindDefByInstance(instance);
    if (!def) return NULL;
    return CSF_FindOverrideForSlot(def, slot);
}


/* -- Dispatcher confidence grades ------------------------------------
 *
 * Every slot gets a best-guess signature-group assignment backed by
 * internal analysis notes.  The grades below indicate how much we trust
 * the assignment; lower grades produce louder bind-time logging so
 * modders can report mis-routings.
 *
 *   PROVEN    -name + signature cross-verified against live decomp
 *               (Destructor, OnInit, GetName).
 *   VERIFIED  -behavior wired through CSF in real scenarios and the
 *               signature is consistent across every donor we checked
 *               (OnTurnBeginQueued, OnRemove, OnStackChange, etc.).
 *   HIGH      -CSV-named slot with a "high" rating in vtable_slots_for_GON
 *               and a decomp signature that's unambiguous.
 *   MEDIUM    -CSV name exists but signature or chain semantics have
 *               not been exercised end-to-end.
 *   LOW       -weak CSV name guess OR the slot has no CSV name at all
 *               but the signature-group consensus is clear.
 *   NONE      -unnamed slot; only the Ghidra-inferred signature is
 *               available and it fits a well-populated family.
 *   STUB      -base vtable stub `ret 0` across all 303 statuses; we
 *               route it through the VoidSelf family as a best guess
 *               so a modder's behavior will still fire.
 *   UNIQUE    -singleton signature OR Ghidra FAPOBase_Initialize
 *               pollution; binding refuses until a dedicated dispatcher
 *               family is added.
 *
 * Anything below HIGH logs a warning at bind time.  UNIQUE refuses to
 * bind and logs an error explaining the slot needs a dispatcher.
 * -------------------------------------------------------------------- */

typedef enum {
    CSF_CONF_UNIQUE = 0,
    CSF_CONF_STUB,
    CSF_CONF_NONE,
    CSF_CONF_LOW,
    CSF_CONF_MEDIUM,
    CSF_CONF_HIGH,
    CSF_CONF_VERIFIED,
    CSF_CONF_PROVEN
} CSF_DispatchConfidence;

static const char* CSF_ConfidenceName(CSF_DispatchConfidence c)
{
    switch (c) {
        case CSF_CONF_PROVEN:   return "proven";
        case CSF_CONF_VERIFIED: return "verified";
        case CSF_CONF_HIGH:     return "high";
        case CSF_CONF_MEDIUM:   return "medium";
        case CSF_CONF_LOW:      return "low";
        case CSF_CONF_NONE:     return "none";
        case CSF_CONF_STUB:     return "stub";
        case CSF_CONF_UNIQUE:   return "unique";
    }
    return "?";
}


/* -- Signature groups ------------------------------------------------
 *
 * These mirror the signature-group table in internal analysis notes.
 * Two kinds of collapses happen on purpose:
 *
 *   • VoidSelf absorbs both VOIDSELF_1 (`void(i64)`) and VOIDSELF_P
 *     (`void(ptr)`); x86-64 passes `self` in rcx either way, so the
 *     two Ghidra-inferred shapes are ABI-identical.
 *
 *   • SelfI64 absorbs SELF_I64 and SELFP_I64 for the same reason, and
 *     also absorbs slot 171's `void(self, INT32)` -the 32-bit arg
 *     rides in the low half of rdx, so calling a `void(self, INT32)`
 *     donor through a `void(self, UINT64)` dispatcher is legal.
 *
 * None is reserved for slots that require their own dedicated family
 * before CSF can route through them (singleton UNIQUE signatures plus
 * the FAPOBase_Initialize-polluted slots 4, 92, 93, 167).  Those
 * slots bind-fail with a "needs dispatcher" error.
 * -------------------------------------------------------------------- */

typedef enum {
    CSF_SIG_None = 0,
    CSF_SIG_VoidSelf,
    CSF_SIG_Dtor,
    CSF_SIG_SelfI64,
    CSF_SIG_SelfI64I64,
    CSF_SIG_SelfI64I64I8,
    CSF_SIG_SelfI32P,
    CSF_SIG_PtrRetOut,
    CSF_SIG_I32PRetOut,
    CSF_SIG_I64SelfpI64,
    CSF_SIG_SelfRetPtr,    /* void* (*)(void* self)  -slot 3 GetTypeInfo */
    CSF_SIG_SelfRetI64     /* UINT64 (*)(void* self) -slot 1 GetTypeId  */
} CSF_SignatureGroup;

static const char* CSF_SigGroupName(CSF_SignatureGroup g)
{
    switch (g) {
        case CSF_SIG_None:         return "(none/unique)";
        case CSF_SIG_VoidSelf:     return "VoidSelf";
        case CSF_SIG_Dtor:         return "Dtor";
        case CSF_SIG_SelfI64:      return "SelfI64";
        case CSF_SIG_SelfI64I64:   return "SelfI64I64";
        case CSF_SIG_SelfI64I64I8: return "SelfI64I64I8";
        case CSF_SIG_SelfI32P:     return "SelfI32P";
        case CSF_SIG_PtrRetOut:    return "PtrRetOut";
        case CSF_SIG_I32PRetOut:   return "I32PRetOut";
        case CSF_SIG_I64SelfpI64:  return "I64SelfpI64";
        case CSF_SIG_SelfRetPtr:   return "SelfRetPtr";
        case CSF_SIG_SelfRetI64:   return "SelfRetI64";
    }
    return "?";
}


/* -- Dispatcher generator macros -------------------------------------
 *
 *  Why macros instead of a single generic dispatcher per signature?
 *  ------------------------------------------------------------------
 *  The dispatcher has to call CSF_FindOverrideForInstance(self, SLOT)
 *  to look up which behavior is bound to the slot it's installed in.
 *  C function pointers can't carry an extra "which slot is this?"
 *  argument, and the game calls through the vtable with the exact
 *  signature the slot expects, so we can't pass it in.  Two options:
 *
 *    (a) Have the dispatcher walk def->custom_vtable looking for a
 *        slot whose entry matches its own function address.  Breaks
 *        as soon as the same dispatcher is installed into two slots
 *        of the same signature on the same status -the scan finds
 *        the first match, not the one that actually called us.
 *
 *    (b) Bake the slot index into the function body, so each
 *        (signature, slot) pair gets its own dedicated dispatcher.
 *        No identity ambiguity, no runtime scan.  This is what the
 *        macros below do.
 *
 *  We use (b).  Adding support for a new slot of an existing
 *  signature is one DEFINE_<SIG>_DISPATCHERS(<slotnum>) line plus
 *  one SLOT_ENTRY row in CSF_GetSlotDispatchInfo.  Adding a brand-new
 *  signature requires a typedef, a DEFINE_<SIG>_DISPATCHERS macro
 *  body, a CSF_SIG_* enum value, and per-slot SLOT_ENTRY rows.
 *
 *  The donor/behavior call ordering logic lives inside the macro
 *  bodies, so every slot of the same signature automatically picks
 *  up the right chain semantics (including slot-5's inverted AFTER;
 *  see DEFINE_DTOR_DISPATCHERS below).
 *
 *  Current stamped families (11 total):
 *     VOIDSELF       void(self)                         -37 real + 80 STUB slots
 *     DTOR           void*(self, UINT64)                -slot 5 only
 *     SELFI64        void(self, UINT64)                 -16 slots
 *     SELFI64I64     void(self, UINT64, UINT64)         -5  slots
 *     SELFI64I64I8   void(self, UINT64, UINT64, char)   -2  slots
 *     SELFI32P       void(self, INT32*)                 -2  slots
 *     PTRRETOUT      void*(self, void* out)             -3  slots
 *     I32PRETOUT     INT32*(self, INT32* out)           -2  slots
 *     I64SELFPI64    UINT64(self, UINT64)               -2  slots
 *     SELFRETPTR     void*(self)                        -slot 3 only
 *     SELFRETI64     UINT64(self)                       -slot 1 only
 *
 *  Slots 0, 1, 3, and 5 form the mandatory quartet every custom
 *  status must route through: GetName (PtrRetOut), GetTypeId
 *  (SelfRetI64), GetTypeInfo (SelfRetPtr), and Destructor (Dtor).
 *  Extensions that leave any of them at the donor's implementation
 *  will silently inherit the donor's identity -the attuned_tuner
 *  reference in extensions/csf_ext_attuned_tuner leans on this
 *  exact behaviour (slot 3 inheritance keeps it inside the donor's
 *  type hierarchy for pool lookups).  SelfRetPtr/SelfRetI64 exist
 *  so GON-declared statuses can override the identity triple
 *  without hand-rolling a trampoline.
 *
 *  20 UNIQUE slots refuse to bind until a dedicated family is added.
 * -------------------------------------------------------------------- */

/* -- Signature 1: void (*)(void* self) -- VoidSelf family */
typedef void (*csf_sig_voidself_fn_t)(void* self);

#define DEFINE_VOIDSELF_DISPATCHERS(slotnum) \
    static void CSF_Dispatch_VoidSelf_Slot##slotnum##_AFTER(void* self) \
    { \
        CSF_SlotOverride* ov; \
        csf_sig_voidself_fn_t donor, behavior; \
        ov = CSF_FindOverrideForInstance(self, slotnum); \
        if (!ov || !ov->behavior_fn) return; \
        donor    = (csf_sig_voidself_fn_t)ov->behavior_donor_fn; \
        behavior = (csf_sig_voidself_fn_t)ov->behavior_fn; \
        if (donor) donor(self); \
        behavior(self); \
    } \
    static void CSF_Dispatch_VoidSelf_Slot##slotnum##_REPLACE(void* self) \
    { \
        CSF_SlotOverride* ov; \
        csf_sig_voidself_fn_t behavior; \
        ov = CSF_FindOverrideForInstance(self, slotnum); \
        if (!ov || !ov->behavior_fn) return; \
        behavior = (csf_sig_voidself_fn_t)ov->behavior_fn; \
        behavior(self); \
    }

/* -- Signature 2: void* (*)(void* self, UINT64 flags) -- Dtor family
 *
 * Scalar-deleting destructor convention.  Currently only slot 5
 * uses this.  AFTER semantics are inverted relative to the other
 * signatures: the behavior runs BEFORE the donor, because the donor
 * destructor is the thing that actually tears the instance down and
 * any observation has to happen before destruction.  Logically it's
 * still "donor owns the authoritative work, behavior wraps around
 * it" -same intent as slot-33 AFTER, just expressed in the opposite
 * call order because the authoritative work is the LAST thing that
 * touches the object. */
typedef void* (*csf_sig_dtor_fn_t)(void* self, UINT64 flags);

#define DEFINE_DTOR_DISPATCHERS(slotnum) \
    static void* CSF_Dispatch_Dtor_Slot##slotnum##_AFTER(void* self, UINT64 flags) \
    { \
        CSF_SlotOverride* ov; \
        csf_sig_dtor_fn_t donor, behavior; \
        ov = CSF_FindOverrideForInstance(self, slotnum); \
        if (!ov || !ov->behavior_fn) return self; \
        donor    = (csf_sig_dtor_fn_t)ov->behavior_donor_fn; \
        behavior = (csf_sig_dtor_fn_t)ov->behavior_fn; \
        behavior(self, flags); \
        if (donor) return donor(self, flags); \
        return self; \
    } \
    static void* CSF_Dispatch_Dtor_Slot##slotnum##_REPLACE(void* self, UINT64 flags) \
    { \
        CSF_SlotOverride* ov; \
        csf_sig_dtor_fn_t behavior; \
        ov = CSF_FindOverrideForInstance(self, slotnum); \
        if (!ov || !ov->behavior_fn) return self; \
        behavior = (csf_sig_dtor_fn_t)ov->behavior_fn; \
        return behavior(self, flags); \
    }

