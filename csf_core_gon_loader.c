/*
 * CSF_GonLoader.c -GON-Driven Status Auto-Registration
 *
 * Reads custom_statuses.gon from disk at framework init time and
 * auto-registers each status definition. GON-defined statuses get:
 *
 *   - A vtable assembled from the base donor + slot overrides
 *   - Generic identity overrides (slots 0-3) that dispatch by sidecar
 *   - MAP0-MAP9 registration entries
 *   - Named sidecar parameters from GON
 *   - C extension overrides applied on top
 *
 * No dependency on the game's GPAK/GON subsystem -uses the CSF
 * built-in GonParser for file I/O.
 *
 * Compilation:
 *   cl /LD /O2 /GS- CustomStatusFramework.c GonParser.c CSF_GonLoader.c
 *       StatusDefs.c DonorVtables.c /Fe:MyMod.dll
 */

#include "csf_core.h"
#include "GonParser.h"
#include "SlotNames.h"


