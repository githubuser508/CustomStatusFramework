/* -- 172-slot dispatch info table --------------------------------
 *
 * Every one of the 172 vtable slots has a single SLOT_ENTRY (or
 * SLOT_UNIQUE) case below.  The switch is the authoritative routing
 * table: CSF_PickDispatcher is a thin wrapper that calls into it.
 *
 * Adding a new dispatcher family:
 *   1) typedef + DEFINE_<SIG>_DISPATCHERS macro body above
 *   2) CSF_SIG_<Sig> enum value and CSF_SigGroupName entry
 *   3) DEFINE_<SIG>_DISPATCHERS(N) invocation for each slot
 *   4) SLOT_ENTRY(N, <Sig>, <CONF>, "<name>") case in the switch
 *
 * Adding a new slot to an existing family only needs steps 3+4.
 * ---------------------------------------------------------------- */

typedef struct {
    int                    slot_index;
    const char*            slot_name;
    CSF_SignatureGroup     sig_group;
    CSF_DispatchConfidence confidence;
    void*                  dispatch_after;
    void*                  dispatch_replace;
} CSF_SlotDispatchInfo;

#define SLOT_ENTRY(slot, sig, conf, name) \
    case slot: \
        info.slot_index      = slot; \
        info.slot_name       = name; \
        info.sig_group       = CSF_SIG_##sig; \
        info.confidence      = CSF_CONF_##conf; \
        info.dispatch_after  = (void*)CSF_Dispatch_##sig##_Slot##slot##_AFTER; \
        info.dispatch_replace = (void*)CSF_Dispatch_##sig##_Slot##slot##_REPLACE; \
        return info;

#define SLOT_UNIQUE(slot, name) \
    case slot: \
        info.slot_index      = slot; \
        info.slot_name       = name; \
        info.sig_group       = CSF_SIG_None; \
        info.confidence      = CSF_CONF_UNIQUE; \
        info.dispatch_after  = NULL; \
        info.dispatch_replace = NULL; \
        return info;

