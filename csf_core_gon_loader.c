/* Check if this instance's type name matches the query.
 * Slot 2 convention: UINT64 type_name_check(void* self, void* nameStr)
 *
 * CRITICAL CONTRACT:
 *   - Returns UINT64 (not int) -caller reads full RAX
 *   - MUST cleanup nameStr before returning (callee-consumed)
 *   - MUST match base-class names "Passive" and "Status" in addition
 *     to the custom name, otherwise the game won't recognize this
 *     instance as a status effect at all and will skip all processing */
UINT64 CSF_GenericTypeNameCheck(void* self, void* nameStr)
{
    fn_string_cleanup cleanup =
        (fn_string_cleanup)(g_gameBase + RVA_STRING_CLEANUP);
    UINT64* p = (UINT64*)nameStr;
    UINT64  size = p[2];
    UINT64  cap  = p[3];
    char*   data = (cap > 15) ? *(char**)p : (char*)p;
    UINT64  result = 0;
    CSF_InstanceSidecar* sc;
    const CSF_StatusDef* def;

    {
        static int s_logged_slot2 = 0;
        if (!s_logged_slot2) {
            s_logged_slot2 = 1;
            SLog("[CSF] SLOT 2 ENTRY: TypeNameCheck called! self=0x%p queried='%.*s' (len=%llu)",
                 self, (int)(size < 64 ? size : 64), data, (unsigned long long)size);
        }
    }

    /* Always match the base-class names -every status is a Passive */
    if (size == 7 && memcmp(data, "Passive", 7) == 0)
        result = 1;
    else if (size == 6 && memcmp(data, "Status", 6) == 0)
        result = 1;
    else
    {
        /* Match the custom status name via sidecar */
        sc = CSF_GetSidecar(self);
        if (sc)
        {
            def = CSF_GetStatusDef(sc->status_def_idx);
            if (def && (int)size == def->name_len &&
                memcmp(data, def->name, size) == 0)
            {
                result = 1;
            }
        }
    }

    /* Callee-consumed: game expects us to clean up the input string */
    cleanup(nameStr);
    return result;
}

/* Return the display name for UI purposes.
 * This is commonly used by the display lookup system. */
void CSF_GenericGetDisplayName(void* self, void* outStr)
{
    CSF_InstanceSidecar* sc = CSF_GetSidecar(self);
    if (sc)
    {
        int defIdx = sc->status_def_idx;
        if (defIdx >= 0 && defIdx < CSF_MAX_STATUSES && g_displayNames[defIdx][0])
        {
            fn_string_assign assign =
                (fn_string_assign)(g_gameBase + RVA_STRING_ASSIGN);
            assign(outStr, g_displayNames[defIdx],
                   (UINT64)strlen(g_displayNames[defIdx]));
            return;
        }
    }
}

/* Slot 28 (GetDisplayDesc) -return display descriptor for UI.
 * Calls the game's display_lookup with the DONOR name to get the base
 * sprite/icon descriptor, then bumps desc[1] so the game treats it as
 * a distinct visual group rather than collapsing it with the donor.
 * desc[6] is the stack count read from the instance. */
void* CSF_GenericGetDisplayDesc(void* self, void* outBuf)
{
    fn_string_ctor    ctor   = (fn_string_ctor)(g_gameBase + RVA_STRING_CTOR);
    fn_display_lookup lookup = (fn_display_lookup)(g_gameBase + RVA_DISPLAY_LOOKUP);
    int* desc;
    CSF_InstanceSidecar* sc;
    const CSF_StatusDef* def;
    UINT64 donorStr[4];

    sc = CSF_GetSidecar(self);
    if (!sc)
    {
        /* Fallback: let the donor's original slot 28 handle it.
         * We don't know which donor at this point, so just zero out. */
        memset(outBuf, 0, 32);
        return outBuf;
    }

    def = CSF_GetStatusDef(sc->status_def_idx);
    if (!def)
    {
        memset(outBuf, 0, 32);
        return outBuf;
    }

    /* Look up the base display descriptor using the DONOR name.
     * The donor name is what the game's standard MAP4 table has valid
     * data for (sentinel, category-tier, flags, etc.).  We then patch
     * desc[0] (the icon index) from the GON config if an override
     * was specified -this is the direct fix for the icon bug, avoiding
     * any dependency on HookGetStatusIcon interception. */
    memset(donorStr, 0, sizeof(donorStr));
    ctor(donorStr, def->donor_name);
    lookup(outBuf, donorStr, 0);

    desc = (int*)outBuf;

    /* -- Icon override: patch desc[0] directly from GON config --
     * desc[0] is the icon index (MAP4_BLOB_OFF_ICON = 0x00).
     * After lookup returns the donor's descriptor, overwrite the icon
     * with the custom status's GON-specified icon value (int_defaults[2]).
     * This is the root fix: the icon now comes from our config, not
     * from the donor's MAP4 entry. */
    {
        const CSF_StatusConfig* cfg = CSF_GetStatusConfig(sc->status_def_idx);
        if (cfg && cfg->int_defaults[2] >= 0)
        {
            int oldIcon = desc[0];
            desc[0] = cfg->int_defaults[2];
            {
                static int s_iconPatchLog = 0;
                if (s_iconPatchLog < 5) {
                    s_iconPatchLog++;
                    SLog("[ICON-FIX] '%s' desc[0]: %d -> %d (GON icon override)",
                         def->name, oldIcon, desc[0]);
                }
            }
        }
    }

    /* desc[1] is the display group/frame index.  Each custom status
     * needs a unique offset from the donor's base to get its own
     * display slot in the sidebar -without this, it collides with
     * the donor or other custom statuses and gets merged/hidden.
     * Old hand-written code used +3 (StatusShare) and +2 (ModRegen).
     * We use +3 as base offset (proven safe for SoulLink donor)
     * plus the def index for uniqueness across multiple GON statuses. */
    desc[1] = desc[1] + 3 + sc->status_def_idx;
    /* desc[6] is the stack count, read from the instance. */
    desc[6] = *(int*)((char*)self + 0x5C);

    {
        static int s_logged = 0;
        if (!s_logged)
        {
            s_logged = 1;
            SLog("[DISPLAY] Generic descriptor for '%s': "
                 "[0]=%d [1]=%d [2]=%d [3]=%d [4]=%d [5]=%d [6]=%d [7]=%d",
                 def->name,
                 desc[0], desc[1], desc[2], desc[3],
                 desc[4], desc[5], desc[6], desc[7]);
        }
    }

    return outBuf;
}

/* Generic on_instance_created callback for GON-defined statuses.
 * Allocates a sidecar and populates named params from defaults. */
static void CSF_GenericOnInstanceCreated(void* instance)
{
    int defIdx;
    CSF_InstanceSidecar* sc;
    const CSF_ParamMap* pm;
    int i;

    /* Find which GON status this instance belongs to by checking vtable */
    for (defIdx = 0; defIdx < CSF_MAX_STATUSES; defIdx++)
    {
        const CSF_StatusDef* def = CSF_GetStatusDef(defIdx);
        if (def && def->custom_vtable == *(void**)instance)
            break;
    }

    if (defIdx >= CSF_MAX_STATUSES)
    {
        SLog("[CSF] GenericOnInstanceCreated: vtable match failed for 0x%p", instance);
        return;
    }

    sc = CSF_AllocSidecar(instance, defIdx);
    if (!sc) return;

    /* Copy named param defaults into sidecar slots */
    pm = &g_paramMaps[defIdx];
    for (i = 0; i < pm->count && i < CSF_MAX_NAMED_PARAMS; i++)
    {
        sc->int_params[i] = pm->descs[i].int_val;
        sc->dbl_params[i] = pm->descs[i].dbl_val;
    }

    SLog("[CSF] Generic sidecar allocated for def %d at 0x%p (%d params)",
         defIdx, instance, pm->count);
}

/* Generic register_in_maps for GON-defined statuses.
 * Clones the donor's MAP0-MAP9 values, then overrides category.
 *
 * Pattern proven by the old hand-written StatusShare/ModRegen code:
 *   1. READ donor values via insert-with-donor-name (returns ptr to existing)
 *   2. INSERT custom entries via insert-with-custom-name
 *   3. WRITE donor's values into the returned pointers
 *   4. Override specific fields (category, flags, etc.)
 *   5. MAP5-MAP8 MUST have no-op callbacks for display visibility
 */
static void CSF_GenericRegisterInMaps_Dispatch(int defIdx)
{
    const CSF_StatusDef* def = CSF_GetStatusDef(defIdx);
    char* reg;
    fn_string_ctor  ctor;
    fn_string_dtor  dtor;
    fn_map_insert   i32Ins;
    fn_map_insert   f64Ins;
    fn_map_insert   d32Ins;
    fn_map_insert   typeAIns;
    fn_map_insert   typeBIns;
    void*           noop;
    void*           val;
    char            str[40];
    int             donor_map1;
    int             donor_map3;
    double          donor_map2;
    unsigned char   donor_map9;
    char            donor_map4[32];
    int             category;
    const CSF_StatusConfig* cfg;
    int i;

    if (!def) return;

    reg      = (char*)(g_gameBase + RVA_REGISTRY);
    ctor     = (fn_string_ctor)(g_gameBase + RVA_STRING_CTOR);
    dtor     = (fn_string_dtor)(g_gameBase + RVA_STRING_DTOR);
    i32Ins   = (fn_map_insert)(g_gameBase + RVA_INT32_INSERT);
    f64Ins   = (fn_map_insert)(g_gameBase + RVA_FLOAT64_INSERT);
    d32Ins   = (fn_map_insert)(g_gameBase + RVA_DATA32_INSERT);
    typeAIns = (fn_map_insert)(g_gameBase + RVA_TYPEA_INSERT);
    typeBIns = (fn_map_insert)(g_gameBase + RVA_TYPEB_INSERT);
    noop     = (void*)(g_gameBase + RVA_NOOP_CALLBACK);

    SLog("[CSF] Registering '%s' in MAP0-MAP9 (cloning donor '%s')",
         def->name, def->donor_name);

    /* -- Step 1: READ donor's existing map values -- */

    memset(str, 0, 40); ctor(str, def->donor_name);
    val = i32Ins(reg + MAP1, str); donor_map1 = *(int*)val; dtor(str);

    memset(str, 0, 40); ctor(str, def->donor_name);
    val = f64Ins(reg + MAP2, str); donor_map2 = *(double*)val; dtor(str);

    memset(str, 0, 40); ctor(str, def->donor_name);
    val = i32Ins(reg + MAP3, str); donor_map3 = *(int*)val; dtor(str);

    memset(str, 0, 40); ctor(str, def->donor_name);
    val = d32Ins(reg + MAP4, str); memcpy(donor_map4, val, 32); dtor(str);

    memset(str, 0, 40); ctor(str, def->donor_name);
    val = typeBIns(reg + MAP9, str); donor_map9 = *(unsigned char*)val; dtor(str);

    SLog("  Donor '%s' reference: Map1=%d Map2=%.4f Map3=0x%X Map9=%d",
         def->donor_name, donor_map1, donor_map2, donor_map3, (int)donor_map9);

    /* -- Step 2: WRITE custom status entries, cloning donor values -- */

    /* MAP0: category (from GON "category" field, default 1 = debuff) */
    category = 1;
    cfg = CSF_GetStatusConfig(defIdx);
    if (cfg) category = cfg->int_defaults[0];

    memset(str, 0, 40); ctor(str, def->name);
    val = i32Ins(reg + MAP0, str); *(int*)val = category; dtor(str);
    SLog("  MAP0 (category) = %d", category);

    /* MAP1: application mode -- override from GON or clone from donor.
     * 0 = accumulate, 1 = presence (SoulLink-style), 2 = overwrite (Doomed-style).
     * GON field "apply_mode" overrides; -1 (default) means clone donor. */
    {
        int map1_val = donor_map1;
        if (cfg && cfg->int_defaults[1] >= 0)
            map1_val = cfg->int_defaults[1];
        memset(str, 0, 40); ctor(str, def->name);
        val = i32Ins(reg + MAP1, str); *(int*)val = map1_val; dtor(str);
        SLog("  MAP1 (app mode) = %d%s", map1_val,
             (cfg && cfg->int_defaults[1] >= 0) ? " (GON override)" : "");
    }

    /* MAP2: multiplier -clone from donor */
    memset(str, 0, 40); ctor(str, def->name);
    val = f64Ins(reg + MAP2, str); *(double*)val = donor_map2; dtor(str);
    SLog("  MAP2 (multiplier) = %.4f", donor_map2);

    /* MAP3: flags -clone from donor */
    memset(str, 0, 40); ctor(str, def->name);
    val = i32Ins(reg + MAP3, str); *(int*)val = donor_map3; dtor(str);
    SLog("  MAP3 (flags) = 0x%X", donor_map3);

    /* MAP4: config blob -clone from donor, then optionally splice the
     * status-icon integer at offset 0x00 (MAP4_BLOB_OFF_ICON).
     *
     * The status-icon glyph index lives at the first int32 of the
     * 32-byte MAP4 blob.  Ground-truth values: Freeze=5, Poison=8,
     * Bleed=14, extending at least into the 200s.  See csf_core.h
     * MAP4_BLOB_OFF_ICON for the offset.
     *
     * The integer is ONE-INDEXED and matches the filename scheme in
     * `public_docs/icons.zip`: index N corresponds to `iconNNNN.png`
     * in the zip (so Freeze = icon0005.png, Poison = icon0008.png,
     * Bleed = icon0014.png). Modders can unzip that archive to browse
     * every available vanilla frame by number.
     *
     * If GON specified `icon <int>` the value is stored in
     * cfg->int_defaults[2] with -1 meaning "clone donor". Anything
     * >= 0 overwrites the cloned donor's icon field in-place. The
     * remaining 28 bytes of the blob are left untouched so the
     * behavior-affecting fields (sentinel at +0x04, category-tier at
     * +0x08, flags at +0x10, rest-are-padding) still match the donor.
     */
    memset(str, 0, 40); ctor(str, def->name);
    val = d32Ins(reg + MAP4, str); memcpy(val, donor_map4, 32); dtor(str);
    {
        int icon_override = -1;
        if (cfg && cfg->int_defaults[2] >= 0)
            icon_override = cfg->int_defaults[2];
        if (icon_override >= 0)
        {
            *(int*)((char*)val + MAP4_BLOB_OFF_ICON) = icon_override;
            SLog("  MAP4 (config) = copied from %s, icon overridden to %d (1-indexed; see icons.zip)",
                 def->donor_name, icon_override);
        }
        else
        {
            SLog("  MAP4 (config) = copied from %s (icon inherited = %d)",
                 def->donor_name,
                 *(int*)((char*)donor_map4 + MAP4_BLOB_OFF_ICON));
        }
    }

    /* MAP5-MAP8: callback slots -no-op (required for display visibility) */
    {
        int mapOffsets[] = { MAP5, MAP6, MAP7, MAP8 };
        for (i = 0; i < 4; i++)
        {
            memset(str, 0, 40); ctor(str, def->name);
            val = typeAIns(reg + mapOffsets[i], str);
            *(void**)val = noop;
            dtor(str);
        }
        SLog("  MAP5-MAP8 (callbacks) = no-op");
    }

    /* MAP9: persistence -clone from donor */
    memset(str, 0, 40); ctor(str, def->name);
    val = typeBIns(reg + MAP9, str); *(unsigned char*)val = donor_map9; dtor(str);
    SLog("  MAP9 (persist) = %d", (int)donor_map9);

    SLog("  MAP registration complete for '%s'", def->name);
}

