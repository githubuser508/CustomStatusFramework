/* Apply C extensions to a GON-defined status after its vtable is built */
static void ApplyExtensions(CSF_StatusDef* def)
{
    int i;
    for (i = 0; i < g_extensionCount; i++)
    {
        if (strcmp(g_extensions[i].status_name, def->name) == 0)
        {
            int slot = g_extensions[i].slot_index;
            if (slot >= 0 && slot < 172 && def->custom_vtable)
            {
                def->custom_vtable[slot] = g_extensions[i].fn_ptr;
                SLog("[CSF]   Extension applied: %s slot %d -> 0x%p",
                     def->name, slot, g_extensions[i].fn_ptr);
            }
        }
    }
}

/* -- String-to-int helpers for GON MAP fields -- */

/* MAP0: category -- buff=0, debuff=1, info=2 */
static int ParseCategory(GonDoc* doc, GonNode* parent, int fallback)
{
    const char* s = Gon_ChildStr(doc, parent, "category", NULL);
    if (s)
    {
        if (strcmp(s, "buff")   == 0) return 0;
        if (strcmp(s, "debuff") == 0) return 1;
        if (strcmp(s, "info")   == 0) return 2;
        /* not a known string -- fall through to int parse */
    }
    return Gon_ChildInt(doc, parent, "category", fallback);
}

/* MAP1: apply_mode -- accumulate=0, presence=1, overwrite=2 */
static int ParseApplyMode(GonDoc* doc, GonNode* parent, int fallback)
{
    const char* s = Gon_ChildStr(doc, parent, "apply_mode", NULL);
    if (s)
    {
        if (strcmp(s, "accumulate") == 0) return 0;
        if (strcmp(s, "presence")   == 0) return 1;
        if (strcmp(s, "overwrite")  == 0) return 2;
    }
    return Gon_ChildInt(doc, parent, "apply_mode", fallback);
}

/* MAP4 splice: optional visual icon override.
 *
 * GON usage:
 *     MyCustomDebuff {
 *         donor   "Bleed"
 *         icon    14     // 1-indexed; see public_docs/icons.zip
 *     }
 *
 * The integer is the 1-INDEXED frame number inside the vanilla
 * status icon atlas. `public_docs/icons.zip` in this directory
 * tree contains every shipped frame as `iconNNNN.png`, so
 * `icon 14` in GON produces the glyph stored as `icon0014.png`
 * (the Bleed droplet). Vanilla ground-truth values observed in
 * the MAP4 blob region: Freeze = 5, Poison = 8, Bleed = 14. Most
 * vanilla statuses have an icon and the index extends at least
 * into the 200s range.
 *
 * No zero-indexed conversion is applied -whatever number the
 * modder writes is stored verbatim in cfg->int_defaults[2] and
 * later written into the MAP4 blob at offset MAP4_BLOB_OFF_ICON
 * (0x00), overwriting the value cloned from the donor. Omitting
 * the `icon` field keeps the donor's icon (sentinel value -1 is
 * used internally to mean "clone donor").
 *
 * WARNING: this is the STATUS icon system (the glyph under a
 * character's portrait when a debuff is active). It is NOT the
 * elemental-icon system (fire/water/ice on abilities, damage
 * numbers, and weapon attunements). Those are entirely separate. */
static int ParseIconOverride(GonDoc* doc, GonNode* parent)
{
    /* -1 = not specified, clone donor's icon */
    return Gon_ChildInt(doc, parent, "icon", -1);
}

/* Parse a single status definition from GON and register it */
static int LoadOneStatus(GonDoc* doc, GonNode* statusNode, int poolIndex)
{
    CSF_StatusDef def;
    const char* donorName;
    const char* displayName;
    int category;
    int apply_mode;
    int icon_override;
    GonNode* overridesNode;
    GonNode* paramsNode;
    int overrideCount;
    const UINT_PTR* donorRvas;
    CSF_StatusConfig cfg;

    memset(&def, 0, sizeof(def));
    memset(&cfg, 0, sizeof(cfg));

    /* -- Read identity fields -- */

    def.name     = statusNode->name;
    def.name_len = (int)strlen(statusNode->name);

    /* Reject status with empty/missing name outright.  GON normally
     * guarantees nonempty object names, but a corrupted or
     * programmatically-edited file might slip one through, and a def
     * with an empty name would collide with every subsequent lookup. */
    if (!def.name || def.name[0] == '\0')
    {
        SLog("[CSF] GON status: empty or missing name, skipping");
        return 0;
    }

    donorName   = Gon_ChildStr(doc, statusNode, "donor", NULL);
    displayName = Gon_ChildStr(doc, statusNode, "display", statusNode->name);
    category      = ParseCategory(doc, statusNode, 1);   /* default: debuff */
    apply_mode    = ParseApplyMode(doc, statusNode, -1); /* -1 = clone donor */
    icon_override = ParseIconOverride(doc, statusNode);  /* -1 = clone donor */

    /* A status without a resolvable donor cannot function.
     * CSF_DefaultBuildVtable relies on the donor's vtable as the
     * baseline for every slot.  Bail loudly rather than register a
     * broken def that would crash the first time one of its slots
     * fired.  An empty-string donor ("donor \"\"") is treated the same
     * as a missing field. */
    if (!donorName || donorName[0] == '\0')
    {
        SLog("[CSF] GON status '%s': missing or empty 'donor' field -a status must clone an existing status to inherit its vtable, skipping", def.name);
        return 0;
    }

    /* Store display name persistently */
    strncpy(g_displayNames[poolIndex], displayName, GON_MAX_STRING_LEN - 1);

    /* Resolve donor -CSF_ResolveDonorVtable walks the generated
     * g_csfDonors table and returns the RVA list for the donor's
     * vtable, or NULL if the name isn't known.  A typo here is the
     * single most common GON authoring mistake, so the log has to name
     * both the status and the unresolved donor so the modder can fix
     * it in one look. */
    donorRvas = CSF_ResolveDonorVtable(donorName);
    if (!donorRvas)
    {
        SLog("[CSF] GON status '%s': donor '%s' not found in donor table -check spelling against the donor list, skipping",
             def.name, donorName);
        return 0;
    }

    def.donor_name   = donorName;
    /* donor_vt_rva = 0 for GON-defined statuses: the vtable pointer RVA
     * isn't in the generated donor tables. HookPrimaryRegistration uses
     * g_pendingDonorRvas slot-content matching as a fallback when this
     * is zero, so the registration hook still works correctly. */
    def.donor_vt_rva = 0;

    SLog("[CSF] GON loading '%s': donor=%s display=\"%s\" category=%d apply_mode=%d icon=%d",
         def.name, donorName, displayName, category, apply_mode, icon_override);

    /* -- Allocate vtable from pool -- */

    if (g_vtablePoolNext >= CSF_VTABLE_POOL_SIZE)
    {
        SLog("[CSF] GON status '%s': vtable pool exhausted, skipping", def.name);
        return 0;
    }
    def.custom_vtable = g_vtablePool[g_vtablePoolNext++];

    /* -- Parse slot overrides -- */

    overridesNode = Gon_Child(doc, statusNode, "slot_overrides");
    overrideCount = 0;

    if (overridesNode)
    {
        GonNode* ov;
        for (ov = Gon_FirstChild(doc, overridesNode); ov; ov = Gon_Next(doc, ov))
        {
            if (overrideCount >= CSF_MAX_SLOT_OVERRIDES)
            {
                SLog("[CSF]   WARNING: too many slot overrides (max %d)", CSF_MAX_SLOT_OVERRIDES);
                break;
            }

            {
                int slotNum;
                CSF_SlotOverride* sov = &g_gonOverrides[poolIndex][overrideCount];

                /* Resolve slot key: try human-readable name first,
                 * fall back to numeric literal.
                 *
                 * GON modders can write either form:
                 *   OnTurnEnd   Marked      // named slot
                 *   41          Marked      // numeric slot
                 */
                slotNum = CSF_ResolveSlotName(ov->name);
                if (slotNum < 0)
                {
                    /* Not a known name -try as a number */
                    char* endp;
                    long parsed = strtol(ov->name, &endp, 10);
                    if (endp != ov->name && *endp == '\0' &&
                        parsed >= 0 && parsed < 172)
                    {
                        slotNum = (int)parsed;
                    }
                    else
                    {
                        SLog("[CSF]   WARNING: '%s' is not a known slot name "
                             "or valid index (0-171), skipping", ov->name);
                        continue;
                    }
                }

                sov->slot_index        = slotNum;
                sov->source_donor      = NULL;
                sov->custom_fn         = NULL;
                sov->behavior_name     = NULL;
                sov->behavior_fn       = NULL;
                sov->behavior_mode     = 0;
                sov->behavior_donor_fn = NULL;

                /* The value is either:
                 *   - A known donor name   -> slot-copy from that donor
                 *   - A registered behavior name -> wire via dispatcher
                 *   - An unknown name      -> parked as pending behavior,
                 *                             may resolve later when the
                 *                             extension DLL publishes its
                 *                             behaviors.  Unknown names
                 *                             are NOT an error because of
                 *                             load-order independence.
                 */
                if (ov->type == GON_TYPE_STRING && ov->str_val[0])
                {
                    const UINT_PTR* srcRvas = CSF_ResolveDonorVtable(ov->str_val);
                    if (srcRvas)
                    {
                        sov->source_donor = ov->str_val;
                        SLog("[CSF]   Slot %d (%s) <- donor '%s'",
                             slotNum, ov->name, ov->str_val);
                    }
                    else
                    {
                        /* Not a donor -- park it as a pending behavior
                         * reference.  Copy the name into persistent
                         * storage since ov->str_val is node-scoped and
                         * the dispatcher will need the name to survive
                         * for process lifetime. */
                        char* nameCopy =
                            g_overrideBehaviorNames[poolIndex][overrideCount];
                        strncpy(nameCopy, ov->str_val, GON_MAX_STRING_LEN - 1);
                        nameCopy[GON_MAX_STRING_LEN - 1] = '\0';
                        sov->behavior_name = nameCopy;

                        if (CSF_FindBehavior(nameCopy))
                        {
                            SLog("[CSF]   Slot %d (%s) <- behavior '%s' "
                                 "(already registered, will bind at vtable "
                                 "build)",
                                 slotNum, ov->name, nameCopy);
                        }
                        else
                        {
                            SLog("[CSF]   Slot %d (%s) <- behavior '%s' "
                                 "(pending -- extension has not published "
                                 "this behavior yet)",
                                 slotNum, ov->name, nameCopy);
                        }
                    }
                }

                overrideCount++;
            }
        }
    }

    if (overrideCount > 0)
    {
        def.slot_overrides      = g_gonOverrides[poolIndex];
        def.slot_override_count = overrideCount;
    }

    /* -- Parse named parameters -- */

    paramsNode = Gon_Child(doc, statusNode, "params");
    if (paramsNode)
    {
        CSF_ParamMap* pm = &g_paramMaps[poolIndex];
        GonNode* pn;

        pm->count = 0;
        for (pn = Gon_FirstChild(doc, paramsNode); pn; pn = Gon_Next(doc, pn))
        {
            if (pm->count >= CSF_MAX_NAMED_PARAMS)
            {
                SLog("[CSF]   WARNING: too many params (max %d)", CSF_MAX_NAMED_PARAMS);
                break;
            }

            strncpy(pm->descs[pm->count].name, pn->name, CSF_PARAM_NAME_LEN - 1);

            if (pn->type == GON_TYPE_NUMBER)
            {
                /* Determine if int or float by checking for decimal point */
                if (strchr(pn->str_val, '.'))
                {
                    pm->descs[pm->count].type    = 1;  /* double */
                    pm->descs[pm->count].dbl_val = pn->dbl_val;
                    pm->descs[pm->count].int_val = pn->int_val;
                    SLog("[CSF]   Param '%s' = %.4f (double)", pn->name, pn->dbl_val);
                }
                else
                {
                    pm->descs[pm->count].type    = 0;  /* int */
                    pm->descs[pm->count].int_val = pn->int_val;
                    pm->descs[pm->count].dbl_val = pn->dbl_val;
                    SLog("[CSF]   Param '%s' = %d (int)", pn->name, pn->int_val);
                }
            }

            pm->count++;
        }
    }

    /* -- Store category, apply_mode, and icon in config --
     * Used by CSF_GenericRegisterInMaps_Dispatch to fill MAP0 (category),
     * MAP1 (apply_mode), and the icon field in the MAP4 blob
     * (MAP4_BLOB_OFF_ICON). A value of -1 in int_defaults[1] or
     * int_defaults[2] means "clone the donor's value for this slot";
     * any other value is an explicit override. See `icons.zip` in this
     * directory tree for the 1-indexed vanilla-icon catalogue that
     * modders should reference when choosing an icon number. */
    cfg.int_defaults[0] = category;
    cfg.int_defaults[1] = apply_mode;    /* -1 = clone from donor */
    cfg.int_defaults[2] = icon_override; /* -1 = clone donor's icon */

    /* -- Set generic lifecycle callbacks -- */
    def.build_vtable        = NULL;   /* use default builder via slot_overrides */
    def.register_in_maps    = g_regMapFns[poolIndex];
    def.on_instance_created = CSF_GenericOnInstanceCreated;
    def.hook_apply_status_ext = NULL;

    /* -- Register the status -- */
    CSF_RegisterStatus(&def);

    /* Store config after registration (needs the registered index) */
    CSF_SetStatusConfig(poolIndex, &cfg);

    return 1;
}


int CSF_LoadGonStatuses(void)
{
    char path[MAX_PATH];
    char baseDir[MAX_PATH];
    char modDir[MAX_PATH];
    DWORD len, modLen;
    GonNode* root;
    GonNode* statuses;
    GonNode* status;
    int count;
    int startIdx;

    SLog("[CSF] === GON-Driven Status Loader ===");

    /* -- Determine mod directory (Mewtator layout: <modDir>/data/) -- */
    modDir[0] = '\0';
    if (g_hSelf) {
        char* slash;
        modLen = GetModuleFileNameA(g_hSelf, modDir, MAX_PATH);
        slash = (modLen > 0) ? strrchr(modDir, '\\') : NULL;
        if (slash) *(slash + 1) = '\0';
        else       modDir[0] = '\0';
    }

    /* -- Determine game directory -- */
    {
        char* slash;
        len = GetModuleFileNameA(NULL, baseDir, MAX_PATH);
        slash = (len > 0) ? strrchr(baseDir, '\\') : NULL;
        if (slash) *(slash + 1) = '\0';
        else       strcpy(baseDir, ".\\");
    }

    /* -- Try loading config file -search order:
     *    1. <modDir>\data\custom_statuses.gon   (Mewtator per-mod layout)
     *    2. <modDir>\custom_statuses.gon         (loose file next to DLL)
     *    3. <gameDir>\mods\custom_statuses.gon   (legacy flat layout)
     *    4. <gameDir>\data\mods\custom_statuses.gon
     * -- */
    {
        int found = 0;

        /* 1. Mewtator layout: <modDir>\data\ */
        if (!found && modDir[0]) {
            snprintf(path, MAX_PATH, "%sdata\\custom_statuses.gon", modDir);
            if (Gon_ParseFile(&g_gonDoc, path)) {
                SLog("[CSF] Loaded (mod data/): %s", path);
                found = 1;
            }
        }

        /* 2. Loose file next to DLL */
        if (!found && modDir[0]) {
            snprintf(path, MAX_PATH, "%scustom_statuses.gon", modDir);
            if (Gon_ParseFile(&g_gonDoc, path)) {
                SLog("[CSF] Loaded (mod root): %s", path);
                found = 1;
            }
        }

        /* 3. Legacy: <gameDir>\mods\ */
        if (!found) {
            snprintf(path, MAX_PATH, "%smods\\custom_statuses.gon", baseDir);
            if (Gon_ParseFile(&g_gonDoc, path)) {
                SLog("[CSF] Loaded (game mods/): %s", path);
                found = 1;
            }
        }

        /* 4. Legacy: <gameDir>\data\mods\ */
        if (!found) {
            snprintf(path, MAX_PATH, "%sdata\\mods\\custom_statuses.gon", baseDir);
            if (Gon_ParseFile(&g_gonDoc, path)) {
                SLog("[CSF] Loaded (game data/mods/): %s", path);
                found = 1;
            }
        }

        if (!found)
        {
            SLog("[CSF] No custom_statuses.gon found -no GON-defined statuses");
            if (modDir[0])
                SLog("[CSF] Searched: %sdata\\, %s, %smods\\, %sdata\\mods\\",
                     modDir, modDir, baseDir, baseDir);
            else
                SLog("[CSF] Searched: %smods\\ and %sdata\\mods\\", baseDir, baseDir);
            return 0;
        }
    }

    /* -- Navigate to custom_statuses block -- */
    root = Gon_Root(&g_gonDoc);
    if (!root) { SLog("[CSF] GON parse failed -no root"); return 0; }

    statuses = Gon_Child(&g_gonDoc, root, "custom_statuses");
    if (!statuses)
    {
        SLog("[CSF] No 'custom_statuses' block in config file");
        return 0;
    }

    /* Remember starting index (C-defined statuses registered first) */
    startIdx = 0;
    {
        const CSF_StatusDef* lastDef = CSF_GetStatusDef(0);
        /* Count existing statuses by scanning until NULL */
        for (startIdx = 0; startIdx < CSF_MAX_STATUSES; startIdx++)
        {
            if (!CSF_GetStatusDef(startIdx)) break;
        }
    }

    SLog("[CSF] GON loader: %d C-defined statuses already registered, "
         "GON statuses start at index %d", startIdx, startIdx);

    /* -- Load each status definition -- */
    count = 0;
    for (status = Gon_FirstChild(&g_gonDoc, statuses);
         status;
         status = Gon_Next(&g_gonDoc, status))
    {
        if (status->type != GON_TYPE_OBJECT)
        {
            SLog("[CSF] Skipping non-object node '%s' in custom_statuses", status->name);
            continue;
        }

        if (LoadOneStatus(&g_gonDoc, status, startIdx + count))
            count++;
    }

    /* -- Apply C extensions to GON-defined statuses -- */
    /* Extensions are applied after all GON statuses are registered,
     * so the vtables exist but haven't been built yet. The extensions
     * will be installed by the vtable build loop in Initialize(). */
    /* Actually, we apply extensions AFTER the vtable build, so we
     * need to defer this. We'll do it in a post-build pass. */

    SLog("[CSF] GON loader: %d status(es) loaded from config", count);
    SLog("[CSF] === GON Loader Complete ===");
    SLog("");

    return count;
}


/* ====================================================================
 *  Post-build extension application
 *
 *  Called after all vtables are built (both C-defined and GON-defined).
 *  Iterates registered extensions and installs their function pointers.
 * ==================================================================== */

void CSF_ApplyAllExtensions(void)
{
    int i;

    if (g_extensionCount == 0) return;

    /* Serialize with CSF_MergeExternalGon and CSFCore_RegisterExtension.
     * CRITICAL_SECTION is recursive -safe to take when called from
     * inside MergeExternalGon which already holds the lock. */
    if (g_csfLockReady) EnterCriticalSection(&g_csfLock);

    SLog("[CSF] Applying %d C extension(s) to GON-defined statuses...", g_extensionCount);

    for (i = 0; i < CSF_MAX_STATUSES; i++)
    {
        const CSF_StatusDef* def = CSF_GetStatusDef(i);
        if (!def) break;

        /* Check each extension for a name match */
        {
            int j;
            for (j = 0; j < g_extensionCount; j++)
            {
                if (strcmp(g_extensions[j].status_name, def->name) == 0)
                {
                    int slot = g_extensions[j].slot_index;
                    if (slot >= 0 && slot < 172 && def->custom_vtable)
                    {
                        def->custom_vtable[slot] = g_extensions[j].fn_ptr;
                        SLog("[CSF]   %s slot %d -> 0x%p",
                             def->name, slot, g_extensions[j].fn_ptr);
                    }
                }
            }
        }
    }

    if (g_csfLockReady) LeaveCriticalSection(&g_csfLock);
}


/* ====================================================================
 *  CSF_MergeExternalGon
 *
 *  Called by the active csf_core instance on behalf of a losing instance
 *  that wants to contribute its own custom_statuses.gon into the
 *  singleton's status table.  The flow is:
 *
 *    1. Parse <modDir>\data\custom_statuses.gon (or fallbacks) into a
 *       scratch GonDoc.
 *    2. Patch-merge that scratch into our own g_gonDoc using Glaiel's
 *       GON merge semantics (default = MERGE, which recursively merges
 *       same-name children and appends new ones).
 *    3. Walk the merged g_gonDoc.custom_statuses block and register any
 *       status whose name is not already in g_statusDefs.  For each new
 *       one we call LoadOneStatus() and then CSF_BuildVtableForStatus()
 *       so that the live vtable exists immediately -extension DLLs
 *       loading after this call see a fully-built status.
 *    4. Re-apply all pending C extensions so any extension that targets
 *       a newly-registered status name gets its vtable slot patched in.
 *
 *  Returns the number of newly-registered statuses (zero is a valid
 *  non-error result).
 *
 *  Note: the scratch GonDoc is kept in BSS (static storage) because
 *  GonDoc is too large to put on the stack.  The merge serializes on
 *  the active-instance singleton, so a single shared scratch is safe.
 * ==================================================================== */
int CSF_MergeExternalGon(const char* modDir)
{
    static GonDoc scratch;   /* BSS -~100KB, don't stack-allocate.
                              * Protected by g_csfLock: see below. */
    char path[MAX_PATH];
    int  found = 0;
    int  startIdx;
    int  preCount;
    int  newlyRegistered = 0;
    int  needsSlash;
    int  lockHeld = 0;
    int  returnValue = 0;
    GonNode* root;
    GonNode* statuses;
    GonNode* status;

    if (!modDir || !modDir[0])
    {
        SLog("[CSF] MergeExternalGon: null/empty modDir");
        return 0;
    }

    /* Serialize every mutation of shared state from here to the end of
     * the function.  Two extension DLLs whose CSFCore_InitOrWait retry
     * timers fire at nearly the same time would otherwise race on the
     * static `scratch` buffer, g_gonDoc, g_statusDefs, g_vtablePool,
     * and g_extensions.  CRITICAL_SECTION is recursive so downstream
     * calls into CSF_ApplyAllExtensions (which also takes the lock)
     * are safe. */
    if (g_csfLockReady) {
        EnterCriticalSection(&g_csfLock);
        lockHeld = 1;
    }

    SLog("[CSF] === MergeExternalGon('%s') ===", modDir);

    /* Does modDir already end in a path separator? */
    {
        size_t mlen = strlen(modDir);
        needsSlash = (mlen > 0 &&
                      modDir[mlen - 1] != '\\' &&
                      modDir[mlen - 1] != '/');
    }

    /* 1. <modDir>\data\custom_statuses.gon (Mewtator per-mod layout) */
    snprintf(path, MAX_PATH, "%s%sdata\\custom_statuses.gon",
             modDir, needsSlash ? "\\" : "");
    if (Gon_ParseFile(&scratch, path))
    {
        SLog("[CSF] MergeExternalGon: loaded %s", path);
        found = 1;
    }

    /* 2. <modDir>\custom_statuses.gon (loose file next to DLL) */
    if (!found)
    {
        snprintf(path, MAX_PATH, "%s%scustom_statuses.gon",
                 modDir, needsSlash ? "\\" : "");
        if (Gon_ParseFile(&scratch, path))
        {
            SLog("[CSF] MergeExternalGon: loaded %s", path);
            found = 1;
        }
    }

    if (!found)
    {
        SLog("[CSF] MergeExternalGon: no custom_statuses.gon found in '%s'",
             modDir);
        goto done;
    }

    /* Defense against a malformed scratch parse leaving partial nodes
     * behind: the Gon_ParseFile check above should be enough, but
     * belt-and-suspenders on a shared BSS buffer is cheap. */
    if (!scratch.parse_ok)
    {
        SLog("[CSF] MergeExternalGon: scratch doc not parse_ok after load");
        goto done;
    }

    /* We can only merge into an already-parsed g_gonDoc.  If the winner
     * never loaded a custom_statuses.gon at all, g_gonDoc.parse_ok is 0
     * and we have nothing to merge into.  In that case, fabricate an
     * empty root so the patch merge creates the structure from scratch. */
    if (!g_gonDoc.parse_ok)
    {
        SLog("[CSF] MergeExternalGon: g_gonDoc empty -initialising empty root");
        memset(&g_gonDoc, 0, sizeof(g_gonDoc));
        /* Manually construct a root OBJECT node (index 0). */
        g_gonDoc.node_count = 1;
        g_gonDoc.nodes[0].name[0]       = '\0';
        g_gonDoc.nodes[0].type          = GON_TYPE_OBJECT;
        g_gonDoc.nodes[0].first_child   = -1;
        g_gonDoc.nodes[0].next_sibling  = -1;
        g_gonDoc.nodes[0].child_count   = 0;
        g_gonDoc.parse_ok               = 1;
    }

    /* Snapshot the current def count before merging -any status whose
     * name already appears in g_statusDefs[0..preCount-1] is 'owned' by
     * a previously-loaded GON and should NOT be re-registered. */
    for (preCount = 0; preCount < CSF_MAX_STATUSES; preCount++)
    {
        if (!CSF_GetStatusDef(preCount)) break;
    }
    startIdx = preCount;

    /* 2.5. Duplicate-name pre-scan.  Walk the scratch doc's
     *      custom_statuses block and unlink any status whose name is
     *      already registered in g_statusDefs.  Without this step,
     *      Gon_PatchMergeDoc's default MERGE mode would recurse into
     *      same-named objects and OVERWRITE existing leaf fields,
     *      causing the in-memory CSF_StatusDef (cached at first load
     *      time) and the merged g_gonDoc to disagree on the status's
     *      parameters.  Modders get a clear warning in the log; first-
     *      loaded declaration wins. */
    {
        GonNode* scratchRoot   = Gon_Root(&scratch);
        GonNode* scratchBlock  = scratchRoot
            ? Gon_Child(&scratch, scratchRoot, "custom_statuses")
            : NULL;

        if (scratchBlock && scratchBlock->first_child >= 0)
        {
            int prevIdx = -1;
            int curIdx  = scratchBlock->first_child;

            while (curIdx >= 0 && curIdx < scratch.node_count)
            {
                GonNode* cur    = &scratch.nodes[curIdx];
                int      nextIdx = cur->next_sibling;
                int      isDup   = 0;
                int      j;

                if (cur->type == GON_TYPE_OBJECT && cur->name[0] != '\0')
                {
                    for (j = 0; j < preCount; j++)
                    {
                        const CSF_StatusDef* existing = CSF_GetStatusDef(j);
                        if (existing && existing->name &&
                            strcmp(existing->name, cur->name) == 0)
                        {
                            isDup = 1;
                            break;
                        }
                    }
                }

                if (isDup)
                {
                    SLog("[CSF] MergeExternalGon: duplicate status '%s' in "
                         "'%s' -first-loaded declaration wins, ignoring "
                         "this mod's redefinition to preserve cached def "
                         "fields",
                         cur->name, modDir);

                    /* Unlink from sibling chain so PatchMergeDoc skips it */
                    if (prevIdx < 0)
                    {
                        scratchBlock->first_child = nextIdx;
                    }
                    else
                    {
                        scratch.nodes[prevIdx].next_sibling = nextIdx;
                    }
                    if (scratchBlock->child_count > 0)
                        scratchBlock->child_count--;
                    /* prevIdx unchanged -the unlinked node is gone */
                }
                else
                {
                    prevIdx = curIdx;
                }

                curIdx = nextIdx;
            }
        }
    }

    /* 3. Patch-merge scratch's root into g_gonDoc's root.  Without any
     *    .append/.merge/.overwrite suffix in scratch, the effective mode
     *    for OBJECT+OBJECT is MERGE: same-name children recurse, new
     *    children are appended.  The duplicate-name pre-scan above
     *    ensured that every top-level status entry in scratch is
     *    genuinely new, so the recursive merge only adds to g_gonDoc
     *    and never overwrites. */
    if (!Gon_PatchMergeDoc(&g_gonDoc, &scratch))
    {
        SLog("[CSF] MergeExternalGon: patch-merge failed (pool exhausted?)");
        goto done;
    }

    SLog("[CSF] MergeExternalGon: patch merge OK (g_gonDoc now %d nodes)",
         g_gonDoc.node_count);

    /* 4. Walk the merged custom_statuses block and register any newly
     *    appeared statuses. */
    root = Gon_Root(&g_gonDoc);
    if (!root)
    {
        SLog("[CSF] MergeExternalGon: no root after merge");
        goto done;
    }
    statuses = Gon_Child(&g_gonDoc, root, "custom_statuses");
    if (!statuses)
    {
        SLog("[CSF] MergeExternalGon: no 'custom_statuses' block after merge");
        goto done;
    }

    for (status = Gon_FirstChild(&g_gonDoc, statuses);
         status;
         status = Gon_Next(&g_gonDoc, status))
    {
        int alreadyExists = 0;
        int i;
        const CSF_StatusDef* existing;
        int newIdx;

        if (status->type != GON_TYPE_OBJECT)
            continue;

        /* Skip if we already registered this status name on a previous
         * init pass (including earlier entries from the winner's own
         * original custom_statuses.gon load). */
        for (i = 0; i < preCount + newlyRegistered; i++)
        {
            existing = CSF_GetStatusDef(i);
            if (existing && existing->name &&
                strcmp(existing->name, status->name) == 0)
            {
                alreadyExists = 1;
                break;
            }
        }

        if (alreadyExists)
        {
            SLog("[CSF] MergeExternalGon: '%s' already registered, skipping",
                 status->name);
            continue;
        }

        /* Bounds-check the pool index before handing it to LoadOneStatus.
         * g_regMapFns, g_paramMaps, g_gonOverrides, g_displayNames, and
         * g_vtablePool are all sized at CSF_MAX_STATUSES. */
        newIdx = startIdx + newlyRegistered;
        if (newIdx >= CSF_MAX_STATUSES)
        {
            SLog("[CSF] MergeExternalGon: status table full (%d), "
                 "dropping '%s' and any remaining merged statuses",
                 CSF_MAX_STATUSES, status->name);
            break;
        }

        if (LoadOneStatus(&g_gonDoc, status, newIdx))
        {
            /* Build the vtable for this freshly-registered status right
             * now -we're running post-init, so the main Initialize()
             * build loop has already gone by. */
            CSF_BuildVtableForStatus(newIdx);
            newlyRegistered++;
            SLog("[CSF] MergeExternalGon: registered '%s' at idx %d",
                 status->name, newIdx);
        }
    }

    /* 5. Re-apply all pending C extensions.  Any extension registered
     *    by a loser's csf_ext DLL that targets one of the just-added
     *    statuses will now be bound to its vtable slot.  Existing
     *    extensions get re-applied to still-existing slots; this is a
     *    no-op for them because the slot contents are unchanged.
     *    ApplyAllExtensions re-enters the lock recursively. */
    if (newlyRegistered > 0)
        CSF_ApplyAllExtensions();

    SLog("[CSF] MergeExternalGon: %d new status(es) registered from '%s'",
         newlyRegistered, modDir);

    returnValue = newlyRegistered;

done:
    if (lockHeld) LeaveCriticalSection(&g_csfLock);
    return returnValue;
}
