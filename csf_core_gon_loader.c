/* Return the dispatcher for a given (slotIndex, chainMode), or NULL
 * if the slot has no dispatcher family or the index is out of range.
 * NULL is the caller's signal to park the override as pending and
 * log a miss -CSF_ResolveBehaviorOverride handles that path. */
static void* CSF_PickDispatcher(int slotIndex, int chainMode)
{
    CSF_SlotDispatchInfo info;
    if (slotIndex < 0 || slotIndex >= 172) return NULL;
    info = CSF_GetSlotDispatchInfo(slotIndex);
    return (chainMode == CSF_CHAIN_AFTER)
         ? info.dispatch_after
         : info.dispatch_replace;
}


/* -- Override resolution + pending sweep --------------------------- */

int CSF_ResolveBehaviorOverride(CSF_StatusDef* def, CSF_SlotOverride* ov)
{
    const CSF_Behavior* beh;
    CSF_SlotDispatchInfo slotInfo;
    void* dispatcher;
    const char* slotLabel;

    if (!def || !ov || !ov->behavior_name || !ov->behavior_name[0])
        return 0;

    beh = CSF_FindBehavior(ov->behavior_name);
    if (!beh)
    {
        /* Pending: leave behavior_fn NULL; the sweep triggered by
         * CSF_RegisterBehavior will revisit this override later. */
        return 0;
    }

    /* Advisory slot check: warn but don't refuse if the override's
     * slot doesn't match the behavior's preferred slot.  Modders
     * occasionally have legitimate reasons to bind a -1 ("any slot")
     * behavior onto a specific slot. */
    if (beh->slot_index >= 0 && beh->slot_index != ov->slot_index)
    {
        SLog("[CSF]   NOTE: behavior '%s' is declared for slot %d but "
             "being bound to slot %d on status '%s' -- proceeding, but "
             "the author should double-check the signature",
             beh->name, beh->slot_index, ov->slot_index, def->name);
    }

    /* Resolve the slot's dispatch info up front so we can tag every
     * log line with the confidence grade + signature family.  The
     * GetSlotDispatchInfo switch is the single source of truth for
     * the 172-slot routing. */
    if (ov->slot_index < 0 || ov->slot_index >= 172)
    {
        SLog("[CSF]   ERROR: behavior '%s' targets slot %d on status "
             "'%s', which is out of range [0..171] -- refusing bind",
             beh->name, ov->slot_index, def->name);
        return 0;
    }
    slotInfo = CSF_GetSlotDispatchInfo(ov->slot_index);
    slotLabel = slotInfo.slot_name ? slotInfo.slot_name : "(unnamed)";

    if (slotInfo.sig_group == CSF_SIG_None)
    {
        /* UNIQUE slot (singleton signature or FAPOBase_Initialize
         * symbol pollution).  No dispatcher family exists yet; the
         * override stays pending until a dedicated dispatcher is added.
         * Log loudly so modders can file a report against the
         * specific slot. */
        SLog("[CSF]   ERROR: slot %d (%s) is UNIQUE -- no dispatcher "
             "family routes it yet.  Behavior '%s' on status '%s' will "
             "not bind.  Please file a report requesting a dedicated "
             "dispatcher family for this slot.",
             ov->slot_index, slotLabel, beh->name, def->name);
        return 0;
    }

    dispatcher = (beh->chain_mode == CSF_CHAIN_AFTER)
               ? slotInfo.dispatch_after
               : slotInfo.dispatch_replace;
    if (!dispatcher)
    {
        SLog("[CSF]   ERROR: slot %d (%s) has signature family %s but "
             "no %s dispatcher was stamped out -- DEFINE_<SIG>_DISPATCHERS"
             "(%d) is missing above.  Refusing to bind '%s' on '%s'.",
             ov->slot_index, slotLabel,
             CSF_SigGroupName(slotInfo.sig_group),
             (beh->chain_mode == CSF_CHAIN_AFTER) ? "AFTER" : "REPLACE",
             ov->slot_index, beh->name, def->name);
        return 0;
    }

    /* Capture the donor's original slot fn BEFORE we overwrite it.
     * Only needed for AFTER mode, but cheap to always read. */
    ov->behavior_donor_fn = def->custom_vtable
        ? def->custom_vtable[ov->slot_index]
        : NULL;
    ov->behavior_fn    = beh->fn;
    ov->behavior_mode  = beh->chain_mode;

    /* Install the dispatcher into the slot itself.  From this point
     * on, every call to the slot on an instance of this status will
     * enter our dispatcher, walk the vtable back to the def, and
     * fan out to (donor, behavior) or (behavior) per chain mode. */
    if (def->custom_vtable)
        def->custom_vtable[ov->slot_index] = dispatcher;

    /* Confidence-tagged bind log.  HIGH and above bind silently at
     * INFO level; MEDIUM emits a gentler note; LOW/NONE/STUB emit a
     * warning so modders know the assignment is a best guess and can
     * double-check the arg shape at runtime.  UNIQUE was already
     * handled above and never reaches this point. */
    if (slotInfo.confidence >= CSF_CONF_HIGH)
    {
        SLog("[CSF]   Behavior bound: %s slot %d (%s) <- '%s' "
             "(chain=%s, sig=%s, conf=%s, donor_fn=0x%p, behavior_fn=0x%p)",
             def->name, ov->slot_index, slotLabel, beh->name,
             (beh->chain_mode == CSF_CHAIN_AFTER) ? "after" : "replace",
             CSF_SigGroupName(slotInfo.sig_group),
             CSF_ConfidenceName(slotInfo.confidence),
             ov->behavior_donor_fn, ov->behavior_fn);
    }
    else if (slotInfo.confidence == CSF_CONF_MEDIUM)
    {
        SLog("[CSF]   Behavior bound (MEDIUM conf): %s slot %d (%s) <- '%s' "
             "(chain=%s, sig=%s, conf=medium, donor_fn=0x%p, behavior_fn=0x%p) "
             "-- signature has not been exercised end-to-end; verify arg "
             "shape matches %s if behavior misbehaves",
             def->name, ov->slot_index, slotLabel, beh->name,
             (beh->chain_mode == CSF_CHAIN_AFTER) ? "after" : "replace",
             CSF_SigGroupName(slotInfo.sig_group),
             CSF_SigGroupName(slotInfo.sig_group));
    }
    else  /* LOW / NONE / STUB */
    {
        SLog("[CSF]   WARNING: Behavior bound with %s confidence: %s slot "
             "%d (%s) <- '%s' (chain=%s, sig=%s, donor_fn=0x%p, "
             "behavior_fn=0x%p).  The signature-family assignment for this "
             "slot is a best guess; if the behavior crashes or misbehaves, "
             "please file a report naming slot %d and the observed crash "
             "signature.",
             CSF_ConfidenceName(slotInfo.confidence),
             def->name, ov->slot_index, slotLabel, beh->name,
             (beh->chain_mode == CSF_CHAIN_AFTER) ? "after" : "replace",
             CSF_SigGroupName(slotInfo.sig_group),
             ov->behavior_donor_fn, ov->behavior_fn,
             ov->slot_index);
    }
    return 1;
}

void CSF_ResolvePendingBehaviorBindings(const char* newlyRegisteredName)
{
    int i;

    if (g_csfLockReady) EnterCriticalSection(&g_csfLock);

    for (i = 0; i < CSF_MAX_STATUSES; i++)
    {
        CSF_StatusDef* def = (CSF_StatusDef*)CSF_GetStatusDef(i);
        int j;
        if (!def) break;
        if (!def->slot_overrides) continue;

        for (j = 0; j < def->slot_override_count; j++)
        {
            CSF_SlotOverride* ov = &def->slot_overrides[j];
            if (!ov->behavior_name || !ov->behavior_name[0]) continue;
            if (ov->behavior_fn) continue;  /* already bound */

            /* Fast reject: if we know which behavior name just landed,
             * skip overrides that reference a different name. */
            if (newlyRegisteredName &&
                strcmp(ov->behavior_name, newlyRegisteredName) != 0)
                continue;

            CSF_ResolveBehaviorOverride(def, ov);
        }
    }

    if (g_csfLockReady) LeaveCriticalSection(&g_csfLock);
}

int CSF_RegisterBehavior(const char* name, int slotIndex, int chainMode, void* fn)
{
    int i;
    CSF_Behavior* slot;

    if (!name || !name[0] || !fn) return 0;
    if (chainMode != CSF_CHAIN_AFTER && chainMode != CSF_CHAIN_REPLACE)
    {
        SLog("[CSF] RegisterBehavior('%s'): invalid chain_mode %d",
             name, chainMode);
        return 0;
    }

    if (g_csfLockReady) EnterCriticalSection(&g_csfLock);

    /* Idempotent insert / replace by name. */
    slot = NULL;
    for (i = 0; i < g_behaviorCount; i++)
    {
        if (strcmp(g_behaviors[i].name, name) == 0)
        {
            slot = &g_behaviors[i];
            break;
        }
    }

    if (!slot)
    {
        if (g_behaviorCount >= CSF_MAX_BEHAVIORS)
        {
            SLog("[CSF] RegisterBehavior('%s'): table full "
                 "(CSF_MAX_BEHAVIORS=%d)", name, CSF_MAX_BEHAVIORS);
            if (g_csfLockReady) LeaveCriticalSection(&g_csfLock);
            return 0;
        }
        slot = &g_behaviors[g_behaviorCount++];
        strncpy(slot->name, name, GON_MAX_STRING_LEN - 1);
        slot->name[GON_MAX_STRING_LEN - 1] = '\0';
    }

    slot->slot_index = slotIndex;
    slot->chain_mode = chainMode;
    slot->fn         = fn;

    SLog("[CSF] Behavior registered: %s (slot %d, chain=%s, fn=0x%p)",
         slot->name, slot->slot_index,
         (slot->chain_mode == CSF_CHAIN_AFTER) ? "after" : "replace",
         slot->fn);

    /* Sweep any pending overrides that were waiting for THIS name.
     * We're already holding the lock; ResolvePendingBehaviorBindings
     * takes it recursively, which is fine (CRITICAL_SECTION). */
    CSF_ResolvePendingBehaviorBindings(name);

    if (g_csfLockReady) LeaveCriticalSection(&g_csfLock);
    return 1;
}


/* ====================================================================
 *  Named Sidecar Parameter Access
 *
 *  CSF_SidecarInt/CSF_SidecarDbl look up a parameter by name in
 *  the status definition's param map, then read from the sidecar's
 *  int_params/dbl_params arrays at the resolved index.
 * ==================================================================== */

int CSF_SidecarInt(CSF_InstanceSidecar* sc, const char* paramName)
{
    const CSF_ParamMap* pm;
    int i;

    if (!sc || sc->status_def_idx < 0) return 0;

    pm = &g_paramMaps[sc->status_def_idx];
    for (i = 0; i < pm->count; i++)
    {
        if (strcmp(pm->descs[i].name, paramName) == 0)
        {
            if (pm->descs[i].type == 0)
                return sc->int_params[i];
            else
                return (int)sc->dbl_params[i];
        }
    }
    return 0;
}

double CSF_SidecarDbl(CSF_InstanceSidecar* sc, const char* paramName)
{
    const CSF_ParamMap* pm;
    int i;

    if (!sc || sc->status_def_idx < 0) return 0.0;

    pm = &g_paramMaps[sc->status_def_idx];
    for (i = 0; i < pm->count; i++)
    {
        if (strcmp(pm->descs[i].name, paramName) == 0)
        {
            if (pm->descs[i].type == 1)
                return sc->dbl_params[i];
            else
                return (double)sc->int_params[i];
        }
    }
    return 0.0;
}


/* ====================================================================
 *  Generic Identity Override Functions (Slots 0–3)
 *
 *  Shared across all GON-defined statuses. They read the status
 *  definition index from the instance's sidecar to dispatch correctly.
 *
 *  Slot 0: get_name       -returns the custom status name
 *  Slot 1: get_type_info  -returns the custom type info struct
 *  Slot 2: type_name_check -compares against the custom name
 *  Slot 3: get_display_name (varies by donor, but commonly slot 89)
 *
 *  These use the same calling convention as the vanilla functions
 *  they replace: RCX = this (instance pointer), RDX = out param.
 * ==================================================================== */

/* Read the status name from the registered definition.
 * Slot 0 convention: void* get_name(void* self, void* outString)
 * Constructs an MSVC SSO string with the status name. */
void* CSF_GenericGetName(void* self, void* outStr)
{
    CSF_InstanceSidecar* sc;

    {
        static int s_logged_slot0 = 0;
        if (!s_logged_slot0) {
            s_logged_slot0 = 1;
            SLog("[CSF] SLOT 0 ENTRY: GenericGetName called! self=0x%p outStr=0x%p", self, outStr);
        }
    }

    sc = CSF_GetSidecar(self);
    if (sc)
    {
        const CSF_StatusDef* def = CSF_GetStatusDef(sc->status_def_idx);
        if (def)
        {
            fn_string_ctor ctor =
                (fn_string_ctor)(g_gameBase + RVA_STRING_CTOR);
            /* Return the custom status name. The display system may not
             * find this in its string table (display registration is a
             * separate issue), but returning the donor name is a
             * regression -it shows "SoulLink" instead of "Tuner". */

            /* -- Prong 2b: Lazy overwrite of instance+0x88 SSO ----
             *
             * The portrait HUD reads +0x88 directly (bypassing vtable
             * slot 0).  The game writes the DONOR name there AFTER
             * apply_status and our HookApplyStatus both return -so
             * overwriting in HookApplyStatus gets clobbered.
             *
             * Instead we do a "lazy" overwrite here in slot 0: every
             * time the game calls GetName through the vtable, we
             * check if +0x88 has been initialized (cap > 0) and still
             * contains the donor name.  If so, we replace it with the
             * custom name.  This fires from post-creation callers
             * (RA+0x126F09, RA+0x806D84) which run after the game
             * has written the donor name to +0x88.
             */
            {
                fn_string_dtor dtor =
                    (fn_string_dtor)(g_gameBase + RVA_STRING_DTOR);
                char* nameSSO = (char*)self + 0x88;
                unsigned long long nameCap =
                    *(unsigned long long*)(nameSSO + 24);
                unsigned long long nameSize =
                    *(unsigned long long*)(nameSSO + 16);

                if (nameCap > 0)
                {
                    /* SSO is initialized. Read current text inline. */
                    const char* curText;
                    if (nameCap > 15)
                        curText = *(const char**)nameSSO;  /* heap */
                    else
                        curText = (const char*)nameSSO;    /* inline */

                    /* Only overwrite if +0x88 does NOT already hold
                     * our custom name (avoid redundant dtor/ctor on
                     * repeated slot 0 calls for the same instance). */
                    if ((int)nameSize != def->name_len ||
                        memcmp(curText, def->name, def->name_len) != 0)
                    {
                        dtor(nameSSO);
                        ctor(nameSSO, def->name);

                        {
                            static int s_lazyLogged = 0;
                            if (s_lazyLogged < 8) {
                                s_lazyLogged++;
                                SLog("[CSF] slot0 lazy overwrite +0x88: "
                                     "'%.*s' -> '%s' (cap was %llu)",
                                     (int)(nameSize < 32 ? nameSize : 32),
                                     curText, def->name, nameCap);
                            }
                        }
                    }
                }
            }

            return ctor(outStr, def->name);
        }
    }
    /* Fallback: return empty string */
    {
        fn_string_ctor ctor = (fn_string_ctor)(g_gameBase + RVA_STRING_CTOR);
        return ctor(outStr, "");
    }
}

